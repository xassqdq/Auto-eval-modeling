# =============================================================================
# 第4节：VIKOR 多准则妥协决策
# =============================================================================

def vikor(matrix: np.ndarray, weights: np.ndarray,
          v: float = 0.5, eps: float = 1e-10) -> dict:
    """
    VIKOR 综合评价。

    Parameters
    ----------
    matrix : 已归一化决策矩阵（正向化后）
    weights: 权重向量
    v      : 决策偏好系数（最大群体效益权重，默认 0.5）

    Returns
    -------
    dict  S, R, Q, ranking
    """
    f_best = matrix.max(axis=0)    # 理想最优值
    f_worst= matrix.min(axis=0)    # 理想最劣值
    denom  = np.where(
        np.abs(f_best - f_worst) < eps, eps, f_best - f_worst
    )
    diff   = (f_best - matrix) / denom            # (m, n)

    S = (weights * diff).sum(axis=1)              # 群体效益值
    R = (weights * diff).max(axis=1)              # 个体最大遗憾

    S_star, S_neg = S.min(), S.max()
    R_star, R_neg = R.min(), R.max()

    dS = S_neg - S_star + eps
    dR = R_neg - R_star + eps
    Q  = v * (S - S_star) / dS + (1 - v) * (R - R_star) / dR

    ranking = Q.argsort() + 1                     # Q 越小排名越高

    return {"S": S, "R": R, "Q": Q, "ranking": ranking}


